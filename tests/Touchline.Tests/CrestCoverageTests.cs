    [Fact]
    public void KeepsDistinctClubsSeparateAndProvidesLocalRecovery()
    {
        var teams = Crests.Enrich(new[] { "Oxford City", "Oxford United", "Austria Salzburg", "RB Salzburg", "BC Rangers", "Rangers" }.Select(Catalog.FromName));
        Assert.All(teams, team => Assert.NotNull(team.Crest));
        Assert.NotEqual(teams[0].Crest, teams[1].Crest);
        Assert.NotEqual(teams[2].Crest, teams[3].Crest);
        Assert.NotEqual(teams[4].Crest, teams[5].Crest);
        var provider = Catalog.FromName("Bournemouth") with { Crest = "https://crests.football-data.org/unavailable.svg" };
        var enriched = Assert.Single(Crests.Enrich([provider]));
        Assert.Equal(provider.Crest, enriched.Crest);
        Assert.StartsWith("/crests/", enriched.CrestFallback);
    }
